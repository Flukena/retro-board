import { PALETTE } from '../ui/palette.js';
import {
  ZONE_CHIP_MIN_WIDTH_PX, ZONE_HEADER_GAP_PX, ZONE_ICON_BUTTON_SIZE_PX, ZONE_ICON_GAP_PX,
} from '../../domain/zone-title.js';

// Browser-only toolbar geometry; palette dependencies must stay out of the relay.
export const ZONE_HEADER_TOOLS_BASE_FONT_PX = 32;
export const ZONE_STRIP_SWATCH_SIZE_PX = 24;
export const ZONE_FONT_VALUE_WIDTH_PX = 32;
export const ZONE_POPUP_ICON_GLYPH_SIZE_PX = 24;
const PALETTE_EDGE_GAP_COUNT = 1;
const FONT_SIZE_BUTTON_COUNT = 2;
const FONT_SIZE_GAP_COUNT = 2;
const STRIP_ICON_COUNT = 6;
const STRIP_GAP_COUNT = 7;
const HEADER_ICON_COUNT = 3;
const PRIMARY_GAP_COUNT = 2;
const PALETTE_ROW_WIDTH_PX = PALETTE.length * ZONE_STRIP_SWATCH_SIZE_PX
  + (PALETTE.length - PALETTE_EDGE_GAP_COUNT) * ZONE_ICON_GAP_PX;
const FONT_SIZE_ROW_WIDTH_PX = FONT_SIZE_BUTTON_COUNT * ZONE_ICON_BUTTON_SIZE_PX
  + ZONE_FONT_VALUE_WIDTH_PX + FONT_SIZE_GAP_COUNT * ZONE_ICON_GAP_PX;
const STRIP_WIDTH_PX = PALETTE_ROW_WIDTH_PX + FONT_SIZE_ROW_WIDTH_PX
  + STRIP_ICON_COUNT * ZONE_ICON_BUTTON_SIZE_PX + STRIP_GAP_COUNT * ZONE_ICON_GAP_PX;
export const ZONE_HEADER_PRIMARY_TOOLS_MIN_PX = ZONE_CHIP_MIN_WIDTH_PX + ZONE_HEADER_GAP_PX
  + HEADER_ICON_COUNT * ZONE_ICON_BUTTON_SIZE_PX + PRIMARY_GAP_COUNT * ZONE_ICON_GAP_PX;
export const ZONE_HEADER_INLINE_TOOLS_MIN_PX = ZONE_HEADER_PRIMARY_TOOLS_MIN_PX
  + STRIP_WIDTH_PX + ZONE_ICON_GAP_PX;

export const ZONE_HEADER_INLINE_TOOLS_MIN_EM = ZONE_HEADER_INLINE_TOOLS_MIN_PX / ZONE_HEADER_TOOLS_BASE_FONT_PX;
export const ZONE_HEADER_PRIMARY_TOOLS_MIN_EM = ZONE_HEADER_PRIMARY_TOOLS_MIN_PX / ZONE_HEADER_TOOLS_BASE_FONT_PX;
